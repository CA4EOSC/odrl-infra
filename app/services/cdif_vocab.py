"""CDIF access vocabularies (SKOS) loaded from config/*.ttl.

CV1 = actions, CV2 = purpose constraints, CV3 = other constraints. The files are
generated by converter/build_skos.py from the SubGroup 2 "Actions and Purposes" sheet.
"""

import os
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional

from rdflib import Graph, URIRef
from rdflib.namespace import DCTERMS, OWL, RDF, SKOS

CONFIG_DIR = Path(os.environ.get("CDIF_VOCAB_DIR", Path(__file__).resolve().parents[2] / "config"))

SCHEMES = {
    "cv1": {"file": "cv1-actions.ttl", "title": "CDIF Actions", "kind": "actions"},
    "cv2": {"file": "cv2-purposes.ttl", "title": "CDIF Purpose Constraints", "kind": "purposes"},
    "cv3": {"file": "cv3-constraints.ttl", "title": "CDIF Other Constraints", "kind": "constraints"},
}

# Prefixes used for compact IRIs in policies (must match the policy @context).
PREFIXES = {
    "odrl": "http://www.w3.org/ns/odrl/2/",
    "cc": "http://creativecommons.org/ns#",
    "dpv": "https://w3id.org/dpv#",
    "cv1": "https://odrl.codata.org/cv1/",
    "cv2": "https://odrl.codata.org/cv2/",
    "cv3": "https://odrl.codata.org/cv3/",
}


def compact(iri: str) -> str:
    for prefix, ns in PREFIXES.items():
        if iri.startswith(ns):
            return f"{prefix}:{iri[len(ns):]}"
    return iri


def _text(g: Graph, s: URIRef, p: URIRef) -> List[str]:
    return sorted(str(o) for o in g.objects(s, p))


def _concept(g: Graph, s: URIRef, collections: Dict[URIRef, List[str]]) -> Dict[str, Any]:
    matches = [str(o) for o in g.objects(s, SKOS.exactMatch)]
    # Policies use the established external term (ODRL/CC for actions, DPV for purposes)
    # when the CDIF concept maps to one exactly; otherwise the CDIF concept itself.
    preferred = next((m for m in matches if compact(m) != m), None)
    replaced_by = g.value(s, DCTERMS.isReplacedBy)
    return {
        "iri": str(s),
        "id": compact(str(s)),
        "value": compact(preferred) if preferred else compact(str(s)),
        "label": str(g.value(s, SKOS.prefLabel) or s),
        "definition": next(iter(_text(g, s, SKOS.definition)), None),
        "notes": _text(g, s, SKOS.scopeNote) + _text(g, s, SKOS.note),
        "exactMatch": matches,
        "broader": [compact(str(o)) for o in g.objects(s, SKOS.broader)],
        "related": [compact(str(o)) for o in g.objects(s, SKOS.related)],
        "deprecated": bool(g.value(s, OWL.deprecated)),
        "replacedBy": compact(str(replaced_by)) if replaced_by else None,
        "collections": collections.get(s, []),
    }


@lru_cache(maxsize=None)
def load_scheme(key: str) -> Dict[str, Any]:
    meta = SCHEMES[key]
    path = CONFIG_DIR / meta["file"]
    if not path.exists():
        return {"scheme": key, "title": meta["title"], "available": False, "concepts": []}
    g = Graph().parse(path, format="turtle")

    collections: Dict[URIRef, List[str]] = {}
    for col in g.subjects(RDF.type, SKOS.Collection):
        label = str(g.value(col, SKOS.prefLabel) or col)
        for m in g.objects(col, SKOS.member):
            collections.setdefault(m, []).append(label)

    concepts = [_concept(g, s, collections) for s in g.subjects(RDF.type, SKOS.Concept)]
    # express replacements the way policies write them (e.g. cv1:modify -> odrl:modify)
    value_of = {c["id"]: c["value"] for c in concepts}
    for c in concepts:
        if c["replacedBy"]:
            c["replacedBy"] = value_of.get(c["replacedBy"], c["replacedBy"])
    concepts.sort(key=lambda c: (c["deprecated"], c["label"].lower()))
    return {
        "scheme": key,
        "title": meta["title"],
        "namespace": PREFIXES[key],
        "available": True,
        "count": len(concepts),
        "concepts": concepts,
    }


def all_schemes() -> Dict[str, Any]:
    return {
        "prefixes": PREFIXES,
        **{SCHEMES[k]["kind"]: load_scheme(k) for k in SCHEMES},
    }


def _index(key: str) -> Dict[str, Dict[str, Any]]:
    """Look up concepts by any of their identifiers (CDIF IRI/id, or the value used in policies)."""
    idx: Dict[str, Dict[str, Any]] = {}
    for c in load_scheme(key)["concepts"]:
        for k in (c["iri"], c["id"], c["value"]):
            idx.setdefault(k, c)
    return idx


def lookup_action(value: str) -> Optional[Dict[str, Any]]:
    return _index("cv1").get(value)


def policy_warnings(policy: Dict[str, Any]) -> List[str]:
    """Non-blocking hints: deprecated CDIF actions and purposes not in CV2."""
    warnings: List[str] = []
    purposes = _index("cv2")
    purpose_operands = {"odrl:purpose", "oac:Purpose", "purpose"}
    for rule_key in ("odrl:permission", "odrl:prohibition", "odrl:obligation", "odrl:duty",
                     "permission", "prohibition", "obligation", "duty"):
        for i, rule in enumerate(policy.get(rule_key) or []):
            if not isinstance(rule, dict):
                continue
            action = rule.get("odrl:action") or rule.get("action")
            if isinstance(action, dict):
                action = action.get("rdf:value") or action.get("@id") or action.get("value")
                if isinstance(action, dict):
                    action = action.get("@id")
            concept = lookup_action(action) if isinstance(action, str) else None
            if concept and concept["deprecated"]:
                hint = f"; use {concept['replacedBy']}" if concept["replacedBy"] else ""
                warnings.append(f"{rule_key}[{i}]: action '{action}' is deprecated in CDIF CV1{hint}.")
            for j, c in enumerate(rule.get("odrl:constraint") or rule.get("constraint") or []):
                if not isinstance(c, dict):
                    continue
                left = c.get("odrl:leftOperand") or c.get("leftOperand")
                right = c.get("odrl:rightOperand") or c.get("rightOperand")
                if left in purpose_operands and isinstance(right, str) and right and right not in purposes:
                    warnings.append(f"{rule_key}[{i}].constraint[{j}]: purpose '{right}' is not in CDIF CV2.")
    return warnings
